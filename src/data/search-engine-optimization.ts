import type { Locale } from "@/i18n/routing"

/**
 * Central place for the site's canonical URL and social-preview data.
 *
 * `NEXT_PUBLIC_SITE_URL` lets preview deployments advertise their real host,
 * but production always falls back to the Vercel URL.
 */
export const websiteURL = (process.env.NEXT_PUBLIC_SITE_URL ?? "https://kuzminklk.vercel.app").replace(/\/$/, "")

export const siteName = "kuzminklk"

/** Absolute URL helper used by canonical links, hreflang and Open Graph. */
export function absoluteUrl(path: string) {
	return new URL(path, websiteURL).toString()
}

/** Localized Open Graph image (generated by `scripts/generate-og.mjs`). */
export function openGraphImagePath(locale: Locale) {
	return `/open-graph/${locale}.png`
}

/**
 * Open Graph locale codes (language_TERRITORY). Telegram, Facebook, VK and
 * LinkedIn read these, and they must be valid for the language.
 */
export const openGraphLocales: Record<Locale, string> = {
	en: "en_US",
	ru: "ru_RU",
	be: "be_BY",
	pl: "pl_PL",
}
